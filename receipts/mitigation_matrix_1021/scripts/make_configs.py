#!/usr/bin/env python3
"""Generate the private FPM pool configs for the mitigation matrix.

Every lane gets its own directory, pid file, log files, session dir and temp
dir. Nothing outside /tmp/opencode/mitigation_1021 is referenced (except the
read-only php-fpm binary), and every listener is loopback-only in 28980-28995.
"""
import os

BASE = "/tmp/opencode/mitigation_1021"
LANES = BASE + "/lanes"

SPECS = {
    # name: (port, upload_progress, cleanup, memory_limit, post_max_size,
    #        display_errors, backtraces)
    "A_fpm_control":      (28980, 1, 0, "8M",   "8M",  1, 1),
    "B_fpm_mitigated":    (28981, 0, 0, "128M", "8M",  0, 0),
    "C_fpm_m1_only":      (28983, 0, 0, "8M",   "8M",  1, 1),
    "B2_oversize_12M":    (28984, 1, 0, "12M",  "16M", 1, 1),
    "B3_oversize_128M":   (28985, 1, 0, "128M", "16M", 1, 1),
    "B4_unlimited_mem":   (28987, 0, 0, "-1",   "8M",  0, 0),
}

TEMPLATE = """\
; {name} - private pool for the 2026-10-21 mitigation matrix.
; Generated by scripts/make_configs.py; do not hand-edit.
[global]
pid = {d}/run/fpm.pid
error_log = {d}/logs/fpm.log
log_level = notice
daemonize = no
process_control_timeout = 5

[{pool}]
user = davide
group = davide
listen = 127.0.0.1:{port}
listen.allowed_clients = 127.0.0.1
pm = static
pm.max_children = 1
pm.max_requests = 0
catch_workers_output = yes
access.log = {d}/logs/access.log
access.format = "%p|%d|%t|%m|%s|%l"
php_admin_value[error_log] = {d}/logs/php_err.log
php_admin_flag[log_errors] = on
php_admin_value[display_errors] = {display}
php_admin_value[fatal_error_backtraces] = {backtraces}
php_admin_value[session.save_path] = {d}/sessions
php_admin_value[session.upload_progress.enabled] = {up}
php_admin_value[session.upload_progress.cleanup] = {cleanup}
php_admin_value[session.use_strict_mode] = 0
php_admin_value[session.use_only_cookies] = 1
php_admin_value[session.gc_probability] = 0
php_admin_value[memory_limit] = {memory}
php_admin_value[post_max_size] = {post}
php_admin_value[upload_tmp_dir] = {d}/tmp
php_admin_value[sys_temp_dir] = {d}/tmp
"""


def main():
    for name, (port, up, cleanup, memory, post, display, backtraces) in SPECS.items():
        d = os.path.join(LANES, name)
        for sub in ("run", "logs", "sessions", "tmp"):
            os.makedirs(os.path.join(d, sub), exist_ok=True)
        conf = TEMPLATE.format(name=name, d=d, pool=name.split("_")[0].lower(),
                               port=port, up=up, cleanup=cleanup, memory=memory,
                               post=post, display=display, backtraces=backtraces)
        with open(os.path.join(d, "fpm.conf"), "w") as f:
            f.write(conf)
        print("wrote", os.path.join(d, "fpm.conf"), "port", port)


if __name__ == "__main__":
    main()
